logger = logging.getLogger(__name__)

# Azure is imported last so it wins the names it shares with the other providers
# (SQL, Mobile, Firewall, Subnet, Databricks, Users, InputOutput).
_PROVIDER_ORDER = ('generic', 'programming', 'k8s', 'onprem', 'azure')


def _build_base_namespace() -> dict:
    """Namespace with every azure/generic/onprem icon pre-imported, so generated code needs no imports."""
    namespace: dict = {}
    exec('import os\nimport diagrams', namespace)
    exec('from diagrams import Diagram, Cluster, Edge, Node', namespace)
    exec('from diagrams.custom import Custom', namespace)
    exec('from urllib.request import urlretrieve', namespace)
    diagrams_path = os.path.dirname(diagrams.__file__)
    for provider in _PROVIDER_ORDER:
        provider_path = os.path.join(diagrams_path, provider)
        if not os.path.isdir(provider_path):
            continue
        for service_file in sorted(os.listdir(provider_path)):
            if not service_file.endswith('.py') or service_file.startswith('_'):
                continue
            try:
                exec(f'from diagrams.{provider}.{service_file[:-3]} import *', namespace)
            except Exception:
                continue
    return namespace


_BASE_NAMESPACE: Optional[dict] = None


def _new_namespace() -> dict:
    global _BASE_NAMESPACE
    if _BASE_NAMESPACE is None:
        _BASE_NAMESPACE = _build_base_namespace()
    return dict(_BASE_NAMESPACE)


def _describe_exec_error(error: Exception, code: str) -> str:
    """Point at the failing line in the submitted code; a bare exception type is not actionable."""
    detail = f'{type(error).__name__}: {error}'
    lineno = getattr(error, 'lineno', None)
    if lineno is None:
        frames = [f for f in traceback.extract_tb(error.__traceback__) if f.filename == '<string>']
        if frames:
            lineno = frames[-1].lineno
    if lineno is None:
        return f'Error generating diagram: {detail}'
    lines = code.splitlines()
    source = lines[lineno - 1].strip() if 0 < lineno <= len(lines) else ''
    return f'Error generating diagram at line {lineno}: {detail}\n    {source}'


def _save_diagram_files(output_path: str, code: str) -> Optional[str]:
    """Save the diagram code and README files."""
    try:
        # Get the directory and filename
        output_dir = os.path.dirname(output_path)
        filename_base = os.path.basename(output_path)
        
        # Save the diagram code
        code_file_path = os.path.join(output_dir, 'diagram_code.py')
        with open(code_file_path, 'w', encoding='utf-8') as f:
            f.write(f"""\"\"\"
Diagram generation code for {filename_base}
Generated by Azure Diagram MCP Server
\"\"\"

{code}
""")
        
        # Generate and save README
        return code_file_path
    except Exception as e:
        logger.error(f"Error saving diagram files: {e}")
        return None


def _find_closing_paren(code: str, start: int) -> Optional[int]:
    """Index of the ')' matching the '(' that precedes start, skipping parens inside strings."""
    depth = 1
    quote = None
    i = start
    while i < len(code):
        char = code[i]
        if quote:
            if char == '\\':
                i += 2
                continue
            if char == quote:
                quote = None
        elif char in ('"', "'"):
            quote = char
        elif char == '(':
            depth += 1
        elif char == ')':
            depth -= 1
            if depth == 0:
                return i
        i += 1
    return None


def _rewrite_diagram_calls(code: str, output_path: str) -> str:
    """Force every `with Diagram(...)` to render to output_path without opening a viewer."""
    safe_path = output_path.replace('\\', '/')
    parts = []
    cursor = 0
    for match in re.finditer(r'with\s+Diagram\s*\(', code):
        args_start = match.end()
        if args_start < cursor:
            continue
        args_end = _find_closing_paren(code, args_start)
        if args_end is None:
            continue
        args = code[args_start:args_end].strip()
        if 'filename=' in args:
            new_args = re.sub(
                r'filename\s*=\s*[\'\"][^\'\"]*[\'\"]', f"filename=r'{safe_path}'", args
            )
        else:
            separator = ' ' if args.endswith(',') else ', '
            new_args = f'{args}{separator}' if args else ''
            new_args += f"filename=r'{safe_path}'"
        if 'show=' not in args:
            new_args += ', show=False'
        parts.append(code[cursor:args_start])
        parts.append(new_args)
        cursor = args_end
    parts.append(code[cursor:])
    return ''.join(parts)


async def generate_diagram(
    code: str,
    filename: Optional[str] = None,
    timeout: int = 90,
) -> DiagramGenerateResponse:
    """Generate a diagram from Python code using the `diagrams` package (Azure only)."""
    scan_result = await scan_python_code(code)
    if scan_result.has_errors:
        return DiagramGenerateResponse(
            status='error',
            message=f'Security issues found in the code: {scan_result.error_message}',
        )
    if filename is None:
        filename = f'diagram_{uuid.uuid4().hex[:8]}'
    # The PNG travels back with the reply, so this path is never read by the caller.
    # Fixing the directory and reducing the name to its last component keeps a crafted
    # filename from choosing where the server writes.
    output_dir = os.path.join(tempfile.gettempdir(), 'diagrams')
    os.makedirs(output_dir, exist_ok=True)
    output_path = os.path.join(output_dir, os.path.basename(filename))
    try:
        namespace = _new_namespace()
        code = _rewrite_diagram_calls(code, output_path)
        # Cross-platform timeout handling
        def timeout_handler(signum, frame):
            raise TimeoutError(f'Diagram generation timed out after {timeout} seconds')
        
        # Set up timeout mechanism (Unix systems only for signal-based timeout)
        timeout_active = False
        if platform.system() != 'Windows':
            try:
                signal.signal(signal.SIGALRM, timeout_handler)
                signal.alarm(timeout)
                timeout_active = True
            except (AttributeError, OSError):
                # Fallback for systems without SIGALRM support
                pass
        
        # Execute the diagram code
        exec(code, namespace)
        
        # Cancel the alarm if it was set
        if timeout_active:
            signal.alarm(0)
        png_path = f'{output_path}.png'
        if os.path.exists(png_path):            
            # Save diagram code and README files
            code_file_path = _save_diagram_files(output_path, code)
            
            success_message = f'Diagram generated successfully at {png_path}'
            if code_file_path:
                success_message += f'\nAdditional files created:\n- {code_file_path}'
            
            return DiagramGenerateResponse(
                status='success',
                path=png_path,
                message=success_message,
            )
        else:
            return DiagramGenerateResponse(
                status='error',
                message=(
                    f'Diagram file was not created at {png_path}. '
                    'The code must contain a `with Diagram(...):` block.'
                ),
            )
    except TimeoutError as e:
        return DiagramGenerateResponse(status='error', message=str(e))
    except Exception as e:
        return DiagramGenerateResponse(status='error', message=_describe_exec_error(e, code))

