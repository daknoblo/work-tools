def _build_icon_index() -> dict:
    """Scan the diagrams package once; importing every service module is the expensive part."""
    diagrams_path = os.path.dirname(diagrams.__file__)
    exclude_dirs = ['__pycache__', '_template']
    allowed_providers = list(_PROVIDER_ORDER)
    providers = {}
    for provider_name in os.listdir(diagrams_path):
        if provider_name not in allowed_providers:
            continue
        provider_path = os.path.join(diagrams_path, provider_name)
        if not os.path.isdir(provider_path) or provider_name in exclude_dirs:
            continue
        providers[provider_name] = {}
        for service_file in os.listdir(provider_path):
            if not service_file.endswith('.py') or service_file.startswith('_'):
                continue
            service_name = service_file[:-3]
            try:
                service_module = importlib.import_module(
                    f'diagrams.{provider_name}.{service_name}'
                )
                icons = [
                    name
                    for name, obj in inspect.getmembers(service_module)
                    if not name.startswith('_')
                    and inspect.isclass(obj)
                    and hasattr(obj, '_icon')
                ]
                if icons:
                    providers[provider_name][service_name] = sorted(icons)
            except Exception:
                continue
    return providers


_ICON_INDEX: Optional[dict] = None


def list_diagram_icons(
    provider_filter: Optional[str] = None, service_filter: Optional[str] = None
) -> DiagramIconsResponse:
    """List available Azure icons from the diagrams package, with optional filtering."""
    global _ICON_INDEX
    logger.debug(f'Filters - provider: {provider_filter}, service: {service_filter}')
    try:
        if _ICON_INDEX is None:
            _ICON_INDEX = _build_icon_index()
        providers = _ICON_INDEX
        filter_info = {}
        if provider_filter:
            needle = provider_filter.lower()
            providers = {k: v for k, v in providers.items() if needle in k.lower()}
            filter_info['provider'] = provider_filter
        if service_filter:
            needle = service_filter.lower()
            providers = {
                provider: {k: v for k, v in services.items() if needle in k.lower()}
                for provider, services in providers.items()
            }
            providers = {k: v for k, v in providers.items() if v}
            filter_info['service'] = service_filter
        return DiagramIconsResponse(
            providers=providers,
            filtered=bool(filter_info),
            filter_info=filter_info or None,
        )
    except Exception as e:
        logger.exception(f'Error in list_diagram_icons: {str(e)}')
        return DiagramIconsResponse(providers={}, filtered=False, filter_info={'error': str(e)})
